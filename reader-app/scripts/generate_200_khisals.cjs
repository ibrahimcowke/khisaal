const fs = require('fs');
const path = require('path');

const targetPath = path.join(__dirname, '..', 'public', 'data', 'alkhisal.json');
const rawData = fs.readFileSync(targetPath, 'utf8');
const bookData = JSON.parse(rawData);

// 1. Build an index of existing texts and titles to guarantee ZERO DUPLICATES
const existingSignatures = new Set();

function normalizeForCheck(str) {
  if (!str) return '';
  return str
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[^\u0621-\u064A0-9]/g, '')
    .trim();
}

bookData.chapters.forEach((c) => {
  existingSignatures.add(normalizeForCheck(c.title));
  c.blocks.forEach((b) => {
    if (b.text) existingSignatures.add(normalizeForCheck(b.text));
    if (b.items) b.items.forEach((it) => existingSignatures.add(normalizeForCheck(it)));
  });
});

console.log('Indexed existing text signatures:', existingSignatures.size);

